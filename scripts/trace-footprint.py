"""
Traces the tower outline from the Revit model and writes src/lib/twin/towerShape.ts.
  1. SAVE_PRE=pre.glb node (shell pre-cull step)  ->  node dump pre.glb  ->  pre.glb.json  (world-space triangles, aligned + centred)
  2. python3 scripts/trace-footprint.py pre.glb.json > src/lib/twin/towerShape.ts
Needs: numpy opencv-python-headless shapely.  The floor plan is the union of the 10 floor slabs (floors that agree on >= 4 levels),
the podium plan is the solid plan of everything below 10.4 m.
"""
import sys, json, numpy as np, cv2
from shapely.geometry import Polygon
P=json.load(open(sys.argv[1])); tris=[]
for p in P:
    v=np.array(p['verts']).reshape(-1,3); i=np.array(p['idx']).reshape(-1,3); tris.append(v[i])
T=np.concatenate(tris); 
RES=0.1; X0,Z0=-29,-16; W,Hh=int(58/RES),int(32/RES)
ymin=T[:,:,1].min(1); ymax=T[:,:,1].max(1)
def raster(y0,y1):
    sel=(ymax>=y0)&(ymin<=y1)
    m=np.zeros((Hh,W),np.uint8)
    for t in T[sel]:
        pts=np.array([[(x-X0)/RES,(z-Z0)/RES] for x,_,z in t],np.int32)
        cv2.fillPoly(m,[pts],255); cv2.polylines(m,[pts],True,255,1)
    return m
def solid(m, close_m=1.2):
    k=int(close_m/RES)|1
    c=cv2.morphologyEx(m,cv2.MORPH_CLOSE,cv2.getStructuringElement(cv2.MORPH_RECT,(k,k)))
    ff=c.copy(); pad=cv2.copyMakeBorder(ff,1,1,1,1,cv2.BORDER_CONSTANT,value=0)
    mask=np.zeros((pad.shape[0]+2,pad.shape[1]+2),np.uint8)
    cv2.floodFill(pad,mask,(0,0),128)
    ext=(pad[1:-1,1:-1]==128)
    return np.where(ext,0,255).astype(np.uint8)
def contour(s, eps=0.5):
    cs,h=cv2.findContours(s,cv2.RETR_CCOMP,cv2.CHAIN_APPROX_NONE)
    out=[]
    for i,c in enumerate(cs):
        a=cv2.contourArea(c)*RES*RES
        if a<4: continue
        ap=cv2.approxPolyDP(c,eps/RES,True)[:,0,:].astype(float)
        pts=[[round(X0+x*RES,2),round(Z0+y*RES,2)] for x,y in ap]
        out.append({'hole':bool(h[0][i][3]>=0),'area':round(a,1),'pts':pts})
    return out
nrm=np.cross(T[:,1]-T[:,0],T[:,2]-T[:,0]); ln=np.linalg.norm(nrm,axis=1)+1e-9
up=(nrm[:,1]/ln)>0.95; cy=T[:,:,1].mean(1)
def slab(level,tol=0.25):
    m=np.zeros((Hh,W),np.uint8)
    for t in T[up&(abs(cy-level)<tol)]:
        pts=np.array([[(x-X0)/RES,(z-Z0)/RES] for x,_,z in t],np.int32); cv2.fillPoly(m,[pts],255)
    return m
levels=[10.67+3.6*k for k in range(10)]
masks=[slab(l) for l in levels]
ref=np.zeros((Hh,W),np.uint8)
for m in masks: ref=cv2.bitwise_or(ref,m)       # union of all floor slabs
# keep what at least 4 floors agree on (drops one-off balcony/cantilever noise)
cnt=sum((m>0).astype(int) for m in masks); core=((cnt>=4)*255).astype(np.uint8)
def post(m,close_m=1.4,open_m=0.8):
    k=int(close_m/RES)|1; m=cv2.morphologyEx(m,cv2.MORPH_CLOSE,cv2.getStructuringElement(cv2.MORPH_RECT,(k,k)))
    k=int(open_m/RES)|1; return cv2.morphologyEx(m,cv2.MORPH_OPEN,cv2.getStructuringElement(cv2.MORPH_RECT,(k,k)))
core=post(core)
# fill small holes (<12 m2) but keep real voids / open gaps
cs,h=cv2.findContours(core,cv2.RETR_CCOMP,cv2.CHAIN_APPROX_NONE)
for i,c in enumerate(cs):
    if h[0][i][3]>=0 and cv2.contourArea(c)*RES*RES<12: cv2.drawContours(core,[c],-1,255,-1)
fp=contour(core,0.6)
print_=lambda *a,**k:None; print_('floor polygons',[(c['hole'],c['area'],len(c['pts'])) for c in fp], 'total solid m2', round((core>0).sum()*RES*RES))

pod=cv2.morphologyEx(solid(raster(0.3,10.4)),cv2.MORPH_OPEN,cv2.getStructuringElement(cv2.MORPH_RECT,(int(0.6/RES)|1,)*2))
podium=contour(pod,0.6)
outer=[c for c in fp if not c['hole']]; holes=[c for c in fp if c['hole']]
F=Polygon(outer[0]['pts'],[h['pts'] for h in holes]).buffer(0); PD=Polygon(podium[0]['pts']).buffer(0)
def polys(g):
    out=[]
    for p in (list(g.geoms) if hasattr(g,'geoms') else [g]):
        if p.is_empty or p.area<1: continue
        p=p.simplify(0.05)
        out.append({'outer':[[round(x,2),round(y,2)] for x,y in list(p.exterior.coords)[:-1]],'holes':[[[round(x,2),round(y,2)] for x,y in list(r.coords)[:-1]] for r in p.interiors]})
    return out
def ts(ps): return ", ".join("{ outer: %s, holes: %s }"%(json.dumps(p['outer']),json.dumps(p['holes'])) for p in ps)
b=F.bounds
print("""/** Procedural-tower outline traced from the real model (generated by scripts/trace-footprint.py). Metres, model space. */
export interface Poly { outer: [number, number][]; holes: [number, number][][]; }
export const FOOTPRINT: Poly[] = [%s];
export const BAND: Poly[] = [%s];
export const PARAPET: Poly[] = [%s];
export const PODIUM: Poly[] = [%s];
export const FOOTPRINT_BOUNDS = { minX: %s, maxX: %s, minZ: %s, maxZ: %s } as const;"""%(ts(polys(F)),ts(polys(F.buffer(0.18,join_style=2))),ts(polys(F.difference(F.buffer(-0.35,join_style=2)))),ts(polys(PD)),round(b[0],2),round(b[2],2),round(b[1],2),round(b[3],2)))
